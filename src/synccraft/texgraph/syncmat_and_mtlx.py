def extract_syncmat_from_graph(
    graph: TexGraph,
    node_ids: list[str] | None = None,
    *,
    name: str = "Custom Material",
    category: str = "User Presets",
    description: str = "",
    frame_color: str = "#2563EB",
    thumbnail: str = "",
) -> dict[str, Any]:
    """Extract selected node(s) (+ their upstream dependencies) or full graph into a portable `.syncmat` preset."""
    if not graph.nodes:
        raise ValueError("Graph has no nodes to save")

    if node_ids:
        roots = [nid for nid in node_ids if nid in graph.nodes]
        if not roots:
            raise ValueError("None of the selected nodes exist in graph")
        needed: set[str] = set()
        stack = list(roots)
        while stack:
            cur = stack.pop()
            if cur in needed or cur not in graph.nodes:
                continue
            needed.add(cur)
            for ref in graph.nodes[cur].inputs.values():
                dep, _ = _parse_ref(ref)
                if dep in graph.nodes:
                    stack.append(dep)
        ordered = [nid for nid in graph.topological_order() if nid in needed]
        out_nid = roots[-1]
    else:
        ordered = list(graph.topological_order())
        out_nid = (graph.output_material_node or graph.output_node or ordered[-1]).split(".")[0]

    # Normalize positions relative to bounding box top-left (0, 0)
    xs = [float(graph.nodes[nid].pos[0]) for nid in ordered if graph.nodes[nid].pos is not None]
    ys = [float(graph.nodes[nid].pos[1]) for nid in ordered if graph.nodes[nid].pos is not None]
    min_x = min(xs) if xs else 0.0
    min_y = min(ys) if ys else 0.0

    nodes_out: list[dict[str, Any]] = []
    for idx, nid in enumerate(ordered):
        sp = graph.nodes[nid]
        px = (float(sp.pos[0]) - min_x) if sp.pos is not None else float(idx * 260)
        py = (float(sp.pos[1]) - min_y) if sp.pos is not None else 0.0
        nodes_out.append(
            {
                "id": sp.id,
                "op": sp.op,
                "inputs": {k: v for k, v in sp.inputs.items() if _parse_ref(v)[0] in set(ordered)},
                "params": copy.deepcopy(sp.params),
                "pos": [round(px, 1), round(py, 1)],
                "label": sp.label,
            }
        )

    # Also build a compact preview TexDSL snippet for human readability
    try:
        sub_g = TexGraph(64, 64, tileable=graph.tileable, seed=graph.seed, name=_slug(name))
        for nd in nodes_out:
            sub_g.add(nd["op"], id=nd["id"], inputs=nd["inputs"], validate_refs=False, **nd["params"])
        sub_g.set_output(out_nid)
        dsl_code = export_texdsl(sub_g)
    except Exception:
        dsl_code = ""

    return {
        "schema": "synccraft.syncmat/1.0",
        "id": _slug(name),
        "name": str(name).strip() or "Custom Material",
        "category": str(category or "User Presets"),
        "description": str(description or f"Saved subgraph preset ({len(nodes_out)} nodes)"),
        "frame_color": frame_color,
        "builtin": False,
        "output_node": out_nid,
        "thumbnail": thumbnail,
        "nodes": nodes_out,
        "texdsl": dsl_code,
    }


def insert_syncmat_into_graph(
    graph: TexGraph,
    preset: dict[str, Any],
    *,
    pos: tuple[float, float] = (240.0, 140.0),
    wrap_frame: bool = True,
) -> tuple[list[str], str, dict[str, Any] | None]:
    """Instantiate a `.syncmat` preset into ``graph`` with collision-free IDs & optional Comment Frame."""
    raw_nodes = preset.get("nodes") or []
    if not raw_nodes:
        raise ValueError("Preset contains no nodes")

    id_map: dict[str, str] = {}
    for nd in raw_nodes:
        orig_id = str(nd.get("id") or nd.get("op") or "node")
        nid = orig_id
        idx = 1
        while nid in graph.nodes or nid in id_map.values():
            nid = f"{orig_id}_{idx}"
            idx += 1
        id_map[orig_id] = nid

    created_ids: list[str] = []
    ox, oy = float(pos[0]), float(pos[1])
    for idx, nd in enumerate(raw_nodes):
        op = str(nd["op"])
        if op not in NODE_CATALOG:
            raise ValueError(f"Unknown op in .syncmat preset: {op!r}")
        nid = id_map[str(nd.get("id") or op)]
        mapped_inputs: dict[str, str] = {}
        for port_k, raw_ref in (nd.get("inputs") or {}).items():
            base, sub = _parse_ref(str(raw_ref))
            if base in id_map:
                mapped_inputs[port_k] = f"{id_map[base]}.{sub}" if sub else id_map[base]
        rel = nd.get("pos") or [idx * 260, 0]
        sp = NodeSpec(
            id=nid,
            op=op,
            inputs=mapped_inputs,
            params=copy.deepcopy(nd.get("params") or {}),
            pos=(round(ox + float(rel[0]), 1), round(oy + float(rel[1]), 1)),
            label=str(nd.get("label") or ""),
        )
        graph.nodes[nid] = sp
        graph.node_order.append(nid)
        created_ids.append(nid)

    out_orig = str(preset.get("output_node") or raw_nodes[-1].get("id") or "")
    out_id = id_map.get(out_orig, created_ids[-1])
    frame_obj = None
    if wrap_frame and len(created_ids) >= 1:
        fid = f"frame_{len(graph.frames) + 1}_{_slug(str(preset.get('name') or 'preset'))[:14]}"
        frame_obj = {
            "id": fid,
            "title": str(preset.get("name") or "Material Preset"),
            "color": str(preset.get("frame_color") or "#2563EB"),
            "node_ids": list(created_ids),
        }
        graph.frames.append(frame_obj)

    graph._static_cache.clear()
    return created_ids, out_id, frame_obj


def list_all_syncmats() -> list[dict[str, Any]]:
    """Return all built-in + user-saved `.syncmat` presets."""
    items: list[dict[str, Any]] = [copy.deepcopy(v) for v in BUILTIN_SYNCMATS.values()]
    if USER_SYNCMAT_DIR.is_dir():
        for p in sorted(USER_SYNCMAT_DIR.glob("*.syncmat.json")):
            try:
                doc = json.loads(p.read_text(encoding="utf-8"))
                if isinstance(doc, dict) and doc.get("nodes"):
                    doc["builtin"] = False
                    doc["file_path"] = str(p)
                    items.append(doc)
            except Exception:
                continue
    return items


def save_user_syncmat(preset: dict[str, Any]) -> Path:
    """Persist a `.syncmat` preset JSON under `~/.synccraft/syncmats/`."""
    USER_SYNCMAT_DIR.mkdir(parents=True, exist_ok=True)
    slug = _slug(str(preset.get("id") or preset.get("name") or "custom_mat"))
    out_path = USER_SYNCMAT_DIR / f"{slug}.syncmat.json"
    out_path.write_text(json.dumps(preset, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return out_path
