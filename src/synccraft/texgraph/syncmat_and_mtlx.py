"""Reusable `.syncmat` Material/Subgraph Presets & ASWF MaterialX 1.38 / OpenPBR Exporter (`TexGraph v14`).

1. **`.syncmat` (`synccraft.syncmat/1.0`)**:
   - Portable, self-contained node-subgraph / material preset format (similar to Substance `.sbsar` / Blender Asset Library)
   - Built-in commercial preset bank + persistent user preset directory (`~/.synccraft/syncmats/`)
   - Extracts any selected node(s) + upstream DAG slice cleanly and instantiates into any live graph with
     collision-free IDs, shifted layout positions, and an enclosing Comment Frame!
2. **ASWF MaterialX 1.38 + OpenPBR Surface (`.mtlx`)**:
   - Generates valid, standards-compliant MaterialX XML (`open_pbr_surface` or `standard_surface`) ready for
     Maya (Arnold), Houdini (Karma), Unreal Engine 5, Blender, and OpenUSD / Omniverse!
"""
from __future__ import annotations

import copy
import json
from pathlib import Path
import re
from typing import Any
from xml.sax.saxutils import escape as _xml_esc

from .core import NodeSpec, TexGraph, _parse_ref
from .registry import NODE_CATALOG
from .texdsl import export_texdsl

USER_SYNCMAT_DIR = Path.home() / ".synccraft" / "syncmats"


def _slug(name: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9_]+", "_", str(name or "material").strip()).strip("_").lower()
    return s or "material"


# ===========================================================================
# 1. ASWF MaterialX 1.38 + OpenPBR Surface Exporter (`.mtlx`)
# ===========================================================================


def export_materialx_xml(
    stem: str,
    *,
    shader_model: str = "open_pbr_surface",
    has_emissive: bool = False,
    has_opacity: bool = False,
    coat_weight: float = 0.0,
    transmission_weight: float = 0.0,
    subsurface_weight: float = 0.0,
    normal_scale: float = 1.0,
    displacement_scale: float = 0.04,
) -> str:
    """Generate clean ASWF MaterialX 1.38 XML referencing SyncCraft PBR texture outputs."""
    sid = _slug(stem)
    ng = f"NG_{sid}"
    sh = f"SR_{sid}"
    mat = f"M_{sid}"
    disp = f"DS_{sid}"
    f_alb = _xml_esc(f"{stem}.png")
    f_nrm = _xml_esc(f"{stem}_normal.png")
    f_rgh = _xml_esc(f"{stem}_roughness.png")
    f_met = _xml_esc(f"{stem}_metallic.png")
    f_hgt = _xml_esc(f"{stem}_height.png")
    f_ao = _xml_esc(f"{stem}_ao.png")
    f_em = _xml_esc(f"{stem}_emissive.png")

    mtlx_ver = "1.39" if shader_model == "open_pbr_surface" else "1.38"
    lines: list[str] = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<materialx version="{mtlx_ver}" colorspace="lin_rec709">',
        f'  <!-- Generated by SyncCraft Studio (TexGraph v17 / MaterialX {mtlx_ver} / {shader_model}) -->',
        f'  <nodegraph name="{ng}">',
        f'    <image name="tex_albedo" type="color4">',
        f'      <input name="file" type="filename" value="{f_alb}" colorspace="srgb_texture" />',
        f'      <input name="filtertype" type="string" value="closest" />',
        f'    </image>',
        f'    <convert name="albedo_rgb" type="color3">',
        f'      <input name="in" type="color4" nodename="tex_albedo" />',
        f'    </convert>',
        f'    <extract name="albedo_alpha" type="float">',
        f'      <input name="in" type="color4" nodename="tex_albedo" />',
        f'      <input name="index" type="integer" value="3" />',
        f'    </extract>',
        f'    <image name="tex_ao" type="float">',
        f'      <input name="file" type="filename" value="{f_ao}" />',
        f'      <input name="filtertype" type="string" value="closest" />',
        f'    </image>',
        f'    <multiply name="base_color_ao" type="color3">',
        f'      <input name="in1" type="color3" nodename="albedo_rgb" />',
        f'      <input name="in2" type="float" nodename="tex_ao" />',
        f'    </multiply>',
        f'    <image name="tex_roughness" type="float">',
        f'      <input name="file" type="filename" value="{f_rgh}" />',
        f'      <input name="filtertype" type="string" value="closest" />',
        f'    </image>',
        f'    <image name="tex_metallic" type="float">',
        f'      <input name="file" type="filename" value="{f_met}" />',
        f'      <input name="filtertype" type="string" value="closest" />',
        f'    </image>',
        f'    <image name="tex_normal" type="vector3">',
        f'      <input name="file" type="filename" value="{f_nrm}" />',
        f'      <input name="filtertype" type="string" value="closest" />',
        f'    </image>',
        f'    <normalmap name="nrm_map" type="vector3">',
        f'      <input name="in" type="vector3" nodename="tex_normal" />',
        f'      <input name="scale" type="float" value="{float(normal_scale):.3f}" />',
        f'    </normalmap>',
        f'    <image name="tex_height" type="float">',
        f'      <input name="file" type="filename" value="{f_hgt}" />',
        f'      <input name="filtertype" type="string" value="closest" />',
        f'    </image>',
    ]
    if has_emissive:
        lines.extend([
            f'    <image name="tex_emissive" type="color3">',
            f'      <input name="file" type="filename" value="{f_em}" colorspace="srgb_texture" />',
            f'      <input name="filtertype" type="string" value="closest" />',
            f'    </image>',
        ])
    lines.extend([
        f'    <output name="out_base_color" type="color3" nodename="base_color_ao" />',
        f'    <output name="out_opacity" type="float" nodename="albedo_alpha" />',
        f'    <output name="out_roughness" type="float" nodename="tex_roughness" />',
        f'    <output name="out_metallic" type="float" nodename="tex_metallic" />',
        f'    <output name="out_normal" type="vector3" nodename="nrm_map" />',
        f'    <output name="out_height" type="float" nodename="tex_height" />',
    ])
    if has_emissive:
        lines.append('    <output name="out_emissive" type="color3" nodename="tex_emissive" />')
    lines.append('  </nodegraph>')

    if shader_model == "standard_surface":
        lines.extend([
            f'  <standard_surface name="{sh}" type="surfaceshader">',
            f'    <input name="base" type="float" value="1.0" />',
            f'    <input name="base_color" type="color3" nodegraph="{ng}" output="out_base_color" />',
            f'    <input name="metalness" type="float" nodegraph="{ng}" output="out_metallic" />',
            f'    <input name="specular_roughness" type="float" nodegraph="{ng}" output="out_roughness" />',
            f'    <input name="normal" type="vector3" nodegraph="{ng}" output="out_normal" />',
        ])
        if coat_weight > 0.001:
            lines.append(f'    <input name="coat" type="float" value="{float(coat_weight):.3f}" />')
            lines.append('    <input name="coat_roughness" type="float" value="0.08" />')
        if transmission_weight > 0.001 or has_opacity:
            tw = max(float(transmission_weight), 0.35 if has_opacity else 0.0)
            lines.append(f'    <input name="transmission" type="float" value="{tw:.3f}" />')
        if subsurface_weight > 0.001:
            lines.append(f'    <input name="subsurface" type="float" value="{float(subsurface_weight):.3f}" />')
        if has_emissive:
            lines.append('    <input name="emission" type="float" value="1.0" />')
            lines.append(f'    <input name="emission_color" type="color3" nodegraph="{ng}" output="out_emissive" />')
        lines.append('  </standard_surface>')
    else:
        # ASWF OpenPBR Surface 1.0 (Maya / Arnold / Houdini Karma / USD / Unreal 5)
        lines.extend([
            f'  <open_pbr_surface name="{sh}" type="surfaceshader">',
            f'    <input name="base_weight" type="float" value="1.0" />',
            f'    <input name="base_color" type="color3" nodegraph="{ng}" output="out_base_color" />',
            f'    <input name="base_metalness" type="float" nodegraph="{ng}" output="out_metallic" />',
            f'    <input name="specular_roughness" type="float" nodegraph="{ng}" output="out_roughness" />',
            f'    <input name="geometry_normal" type="vector3" nodegraph="{ng}" output="out_normal" />',
            f'    <input name="geometry_opacity" type="float" nodegraph="{ng}" output="out_opacity" />',
        ])
        if coat_weight > 0.001:
            lines.append(f'    <input name="coat_weight" type="float" value="{float(coat_weight):.3f}" />')
            lines.append('    <input name="coat_roughness" type="float" value="0.08" />')
        if transmission_weight > 0.001:
            lines.append(f'    <input name="transmission_weight" type="float" value="{float(transmission_weight):.3f}" />')
        if subsurface_weight > 0.001:
            lines.append(f'    <input name="subsurface_weight" type="float" value="{float(subsurface_weight):.3f}" />')
        if has_emissive:
            lines.append('    <input name="emission_luminance" type="float" value="1.2" />')
            lines.append(f'    <input name="emission_color" type="color3" nodegraph="{ng}" output="out_emissive" />')
        lines.append('  </open_pbr_surface>')

    lines.extend([
        f'  <displacement name="{disp}" type="displacementshader">',
        f'    <input name="displacement" type="float" nodegraph="{ng}" output="out_height" />',
        f'    <input name="scale" type="float" value="{float(displacement_scale):.4f}" />',
        f'  </displacement>',
        f'  <surfacematerial name="{mat}" type="material">',
        f'    <input name="surfaceshader" type="surfaceshader" nodename="{sh}" />',
        f'    <input name="displacementshader" type="displacementshader" nodename="{disp}" />',
        f'  </surfacematerial>',
        '</materialx>',
    ])
    return "\n".join(lines) + "\n"


